'use strict';
const assert = require('node:assert/strict');
const Cloud = require('./cloud-sync.js');
async function main() {
  const code = Cloud.createCode(), second = Cloud.createCode();
  assert.match(code, /^KM1\.[A-Za-z0-9_-]{43}$/); assert.notEqual(code, second);
  const auth = await Cloud.credentials(code);
  assert.notEqual(auth.token, code.slice(4));
  assert.equal(auth.key.extractable, false);
  assert.equal(auth.token, (await Cloud.credentials(code)).token);
  for (const bad of ['', 'KM1.fake', code + '=', 'KM1.' + 'A'.repeat(42) + 'B']) await assert.rejects(() => Cloud.credentials(bad));
  console.log('✓ Secret aléatoire, dérivation séparée et encodage canonique');
  const entry = { meta: { teamName: 'Équipe 🏆', updatedAt: 1 }, data: { currentRound: 2, notes: 'identités et règles' } };
  const envelope = await Cloud.seal(entry, code), again = await Cloud.seal(entry, code);
  assert.notEqual(envelope.iv, again.iv); assert.notEqual(envelope.ciphertext, again.ciphertext);
  assert.deepEqual(await Cloud.open(envelope, code), entry);
  assert.ok(!JSON.stringify(envelope).includes('currentRound'));
  assert.ok(!JSON.stringify(envelope).includes(code));
  await assert.rejects(() => Cloud.open(envelope, second), { code: 'decrypt' });
  const altered = { ...envelope, ciphertext: (envelope.ciphertext[0] === 'A' ? 'B' : 'A') + envelope.ciphertext.slice(1) };
  await assert.rejects(() => Cloud.open(altered, code), { code: 'decrypt' });
  console.log('✓ Chiffrement authentifié, IV distincts, mauvais secret et altération rejetés');
  const large = { ...entry, data: { text: 'données du club '.repeat(10000) } };
  const compact = await Cloud.seal(large, code);
  assert.ok(JSON.stringify(compact).length < JSON.stringify(large).length / 10);
  assert.deepEqual(await Cloud.open(compact, code), large);
  await assert.rejects(() => Cloud.seal({ data: 'x'.repeat(Cloud.MAX_PLAIN) }, code), { code: 'size' });
  await assert.rejects(() => Cloud.open({ v: 1, iv: 'A'.repeat(16), ciphertext: 'A'.repeat(Cloud.MAX_WIRE + 1) }, code), { code: 'invalid' });
  console.log('✓ Compression des grosses carrières et limites de taille');
  const hash = await Cloud.fingerprint(entry);
  assert.equal(hash, await Cloud.fingerprint({ ...entry, meta: { ...entry.meta, updatedAt: 999 } }));
  assert.notEqual(hash, await Cloud.fingerprint({ ...entry, data: { ...entry.data, currentRound: 3 } }));
  console.log('✓ Déduplication indépendante de la date de simple enregistrement');
  const calls = [];
  const fetcher = async (url, options) => { calls.push({ url, ...options }); return new Response(JSON.stringify(options.method === 'GET' ? envelope : { ok: true }), { status: 200, headers: { ETag: '"revision1"' } }); };
  await Cloud.request(code, 'PUT', envelope, undefined, fetcher);
  await Cloud.request(code, 'PUT', envelope, '"revision1"', fetcher);
  const read = await Cloud.request(code, 'GET', undefined, undefined, fetcher);
  await Cloud.request(code, 'DELETE', undefined, '"revision1"', fetcher);
  assert.equal(calls[0].headers['If-None-Match'], '*');
  assert.equal(calls[1].headers['If-Match'], '"revision1"');
  assert.equal(calls[3].headers['If-Match'], '"revision1"');
  assert.equal(calls[0].headers.Authorization, 'Bearer ' + auth.token);
  assert.equal(calls[0].cache, 'no-store');
  assert.equal(calls[0].credentials, 'same-origin');
  assert.ok(!JSON.stringify(calls).includes(code));
  assert.deepEqual(read.envelope, envelope);
  const compressedResponse = await Cloud.request(code, 'GET', undefined, undefined, async () => new Response(JSON.stringify(envelope), {
    headers: { ETag: 'W/"transport-compressed"', 'X-Career-Revision': '"storage-strong"' }
  }));
  assert.equal(compressedResponse.etag, '"storage-strong"');
  await Cloud.request(code, 'PUT', envelope, compressedResponse.etag, fetcher);
  assert.equal(calls.at(-1).headers['If-Match'], '"storage-strong"');
  console.log('✓ Préconditions de création et mise à jour, capacité séparée du secret');
  await assert.rejects(() => Cloud.request(code, 'PUT', envelope, 'old', async () => new Response('{}', { status: 409 })), { code: 409 });
  await assert.rejects(() => Cloud.request(code, 'GET', undefined, undefined, async () => new Response('{}', { status: 503 })), { code: 503 });
  await assert.rejects(() => Cloud.request(code, 'GET', undefined, undefined, async () => { throw new TypeError('offline'); }), { code: 'network' });
  await assert.rejects(() => Cloud.request(code, 'PUT', envelope, 'old', async () => new Response('{}', { status: 200 })), { code: 'revision' });
  console.log('✓ Conflits, panne et confirmation sans révision jamais annoncés comme succès');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
